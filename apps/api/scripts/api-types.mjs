// Generates the website's API types from the API's own OpenAPI document (P3-03): apps/web/src/api/schema.d.ts.
// The document is built in memory from the routes and their Zod schemas, so no server has to run.
//   node scripts/api-types.mjs          writes the file (`pnpm api:types` from the project root)
//   node scripts/api-types.mjs --check  fails when the file is out of date (also checked by the API tests)
import fs from "node:fs";
import { fileURLToPath } from "node:url";
import { register } from "node:module";

// openapi-typescript builds the types with TypeScript's JS compiler API, which TypeScript 7 (this project's compiler) no
// longer has. Inside this script only, its `import "typescript"` is pointed at TypeScript 5 (the "typescript5" package).
const ts5 = import.meta.resolve("typescript5");
register(`data:text/javascript,${encodeURIComponent(
  `export async function resolve(s, c, next) { return s === "typescript" ? { url: ${JSON.stringify(ts5)}, shortCircuit: true } : next(s, c); }`,
)}`);
const { default: openapiTS, astToString } = await import("openapi-typescript");

export const TYPES_FILE = fileURLToPath(new URL("../../web/src/api/schema.d.ts", import.meta.url));

const HEADER = `// GENERATED by apps/api/scripts/api-types.mjs from the API's OpenAPI document. Do not edit by hand:
// change the API's routes or schemas, then run \`pnpm api:types\`. The API tests fail when this file is out of date.
/* biome-ignore-all lint: generated */

`;

/** The current API types, as the file's text. */
export async function apiTypes() {
  // importing the API checks its settings (src/config.ts); give it a database address that is never opened
  process.env.DATABASE_URL ||= "file:./api-types-never-opened.db";
  const { createApp, OPENAPI_DOC } = await import("../src/app.ts");
  const { pino } = await import("pino");
  const app = createApp({ config: { deepseek: {}, gmail: {}, rateLimit: { perMinute: 1, aiPerMinute: 1 } }, prisma: {}, log: pino({ level: "silent" }) });
  const doc = app.getOpenAPI31Document(OPENAPI_DOC);
  return HEADER + astToString(await openapiTS(doc, { alphabetize: true }));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === fs.realpathSync(process.argv[1])) {
  const text = await apiTypes();
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(TYPES_FILE) ? fs.readFileSync(TYPES_FILE, "utf8").replace(/\r\n/g, "\n") : "";
    if (current !== text) {
      console.error("apps/web/src/api/schema.d.ts is out of date. Run: pnpm api:types");
      process.exit(1);
    }
    console.log("API types are up to date.");
  } else {
    fs.mkdirSync(new URL("../../web/src/api/", import.meta.url), { recursive: true });
    fs.writeFileSync(TYPES_FILE, text);
    console.log(`Wrote ${TYPES_FILE}`);
  }
}
